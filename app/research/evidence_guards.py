"""Narrow evidence-boundary and benchmark-relation checks, without source mutation."""

from __future__ import annotations

import re


class IncompleteAISummaryBlockError(ValueError):
    """A marked generated widget lacks a verified end; do not guess author boundaries."""


_AI_START = re.compile(r"^[ \t]*Read AI-generated summary[ \t]*$", re.I | re.M)
_AI_END = re.compile(
    r"^[ \t]*(?:#{1,6}[ \t]+)?Explore other styles:[ \t]*\r?\n"
    r"\s*[-*][ \t]+General summary[ \t]*\r?\n"
    r"\s*[-*][ \t]+Bullet points[ \t]*\r?\n"
    r"\s*[-*][ \t]+Basic explainer[ \t]*(?=\r?\n|$)",
    re.I | re.M,
)
_AI_DISCLAIMER = re.compile(r"Summaries were generated by Google AI\.", re.I)


def author_evidence_text(text: str) -> str:
    """Exclude Google's explicitly bounded three-style generated-summary widget.

    Keep the original author prefix/suffix exactly. Missing or unfamiliar closing
    markers raise rather than silently returning suspect AI prose or losing the
    remainder of an article. Callers may exclude the document with that reason;
    the raw source must remain available for later inspection.
    """
    result = str(text)
    while start := _AI_START.search(result):
        end = _AI_END.search(result, start.end())
        if end is None or not _AI_DISCLAIMER.search(result, start.end(), end.start()):
            raise IncompleteAISummaryBlockError(
                "Marked AI-generated summary lacks a verified Google disclaimer/style footer; "
                "author evidence is unavailable until the boundary is resolved"
            )
        result = result[: start.start()] + result[end.end() :]
    return result


_CRPS = re.compile(
    r"\bCRPS\b|Continuous Ranked Probability Score|"
    r"непрерывн\w*\s+ранжированн\w*\s+вероятностн\w*\s+(?:оценк\w*|показател\w*|балл\w*)",
    re.I,
)
_PERCENT = re.compile(r"\d+(?:[.,]\d+)?\s*(?:%|процент)", re.I)
_IMPROVEMENT = re.compile(
    r"improv\w*|reduc\w*|better|улучш\w*|снижен\w*|сниз\w*|сокращ\w*|сократ\w*",
    re.I,
)
_PERFORMANCE = re.compile(r"CRPS|точност\w*|accuracy|прогноз\w*|forecast\w*|осад\w*", re.I)
_COMPARATOR = re.compile(
    r"(?:по сравнению с|против|лучше(?:,? чем)?|обогнал[аи]?|превзош[её]л|vs\.?|versus|than)"
    r"\s+([A-Z][A-Za-z0-9._-]*(?:\s+\d+(?:\.\d+)?)?)"
)
_DATA_ROLE = r"(?:данн\w*|измерен\w*|наблюден\w*|data(?:sets?)?|measurements?|observations?)"
_EXPLICIT_IMERG_DATA_ROLE = re.compile(
    # A local noun relation, not any occurrence of 'по данным Google' elsewhere.
    rf"{_DATA_ROLE}\s+(?:(?:набора|проекта|from|of)\s+)?IMERG\b|"
    rf"\bIMERG\s+(?:(?:satellite|спутников\w*)\s+)?{_DATA_ROLE}\b|"
    # An explicit definition such as 'IMERG — спутниковый набор данных'.
    rf"\bIMERG\s*(?:[—–:-]|,?\s+(?:это|is|are|то есть))\s*"
    rf"(?:[A-Za-zА-Яа-яЁё-]+\s+){{0,4}}{_DATA_ROLE}\b",
    re.I,
)


def measurement_relation_errors(
    fact_text: str, quoted_evidence: str, source_context: str = ""
) -> list[str]:
    """Preserve the CRPS measurement relation, not just coincident numeric tokens.

    Applies only when the *cited* excerpt describes a CRPS improvement and the
    proposed fact makes a quantified performance claim. Broader source context
    can establish that IMERG is data, never supply a missing competitor/baseline.
    This is deliberately not a universal measurement or semantic verifier.
    """
    if not (
        _CRPS.search(quoted_evidence)
        and _IMPROVEMENT.search(quoted_evidence)
        and _PERCENT.search(fact_text)
        and _PERFORMANCE.search(fact_text)
    ):
        return []
    errors: list[str] = []
    if not _CRPS.search(fact_text):
        errors.append("CRPS measurement lost: a relative score improvement is not generic accuracy")
    if not _IMPROVEMENT.search(fact_text):
        errors.append("CRPS relation lost: preserve improvement, not an absolute accuracy/score")
    if re.search(r"\bIMERG\b", fact_text, re.I) and not _EXPLICIT_IMERG_DATA_ROLE.search(fact_text):
        errors.append(
            "IMERG data role missing: explicitly identify evaluation data/measurements, "
            "not an unnamed comparison baseline"
        )

    context = " ".join((quoted_evidence, source_context))
    imerg_is_data = bool(
        re.search(
            r"(?:data|данн\w*|satellite|спутник\w*|Integrated Multi-satellite Retrievals)"
            r"[^.!?\n]{0,180}\bIMERG\b|"
            r"\bIMERG\b[^.!?\n]{0,180}(?:data|данн\w*|satellite|спутник\w*)",
            context,
            re.I,
        )
    )
    for match in _COMPARATOR.finditer(fact_text):
        comparator = match.group(1).rstrip(".,")
        if comparator.casefold() == "imerg" and imerg_is_data:
            errors.append("IMERG is evaluation data, not a competing forecast model/baseline")
        elif comparator.casefold() not in quoted_evidence.casefold():
            errors.append("CRPS comparison adds a baseline absent from its cited evidence")
    if imerg_is_data and re.search(
        r"модел\w*\s+IMERG\b|\bIMERG\s+(?:model|модел\w*)", fact_text, re.I
    ):
        errors.append("IMERG is evaluation data, not a competing forecast model/baseline")
    return list(dict.fromkeys(errors))

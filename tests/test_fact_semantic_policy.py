@pytest.mark.parametrize("invalid", [False, True])
def test_fact_extractor_gpt5_compat_and_receipt_survives_invalid_response(tmp_path, invalid):
    settings = Settings(data_dir=tmp_path, openrouter_api_key=SecretStr("unit-test-secret"))
    content = "not-json" if invalid else json.dumps(fact_sheet().model_dump())

    def transport(payload, key):
        assert key == "unit-test-secret"
        assert "temperature" not in payload
        assert payload["reasoning"]["effort"] == "low"
        assert payload["provider"]["max_price"] == {"prompt": 0.5, "completion": 2.0}
        return {
            "id": "audit-test",
            "model": "openai/gpt-5.6-luna",
            "usage": {"cost": 0.003, "prompt_tokens": 1000, "completion_tokens": 100},
            "choices": [
                {
                    "finish_reason": "stop",
                    "message": {
                        "content": content,
                        "reasoning": "private hidden reasoning should not be persisted",
                    },
                }
            ],
        }

    generator = OpenRouterFactSheetGenerator(settings, transport=transport)
    if invalid:
        with pytest.raises(OpenRouterResponseError) as error:
            generator.generate(
                event={"id": 7}, documents=fact_documents(), model="openai/gpt-5.6-luna"
            )
        metadata = error.value.billing_metadata
    else:
        result = generator.generate(
            event={"id": 7}, documents=fact_documents(), model="openai/gpt-5.6-luna"
        )
        metadata = result.billing_metadata
    path = Path(metadata["raw_fact_receipt_path"])
    raw = path.read_text()
    receipt = json.loads(raw)
    assert receipt["content"] == content
    assert receipt["cost_accounted_usd"] == 0.003
    assert "unit-test-secret" not in raw and "hidden reasoning" not in raw
    assert stat.S_IMODE(path.stat().st_mode) == 0o600



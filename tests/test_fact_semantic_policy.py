def test_quote_bank_keeps_complete_short_product_price_and_compliance_labels():
    raw = (
        "Flight + hotel · $1,488 Ready for your approval\n\nIllustrative itinerary\n\n"
        "SOC 2 Type II \nCompliant\n\nCASA Tier-2 \nCertified\n\nGoogle \nVerified\n\n"
        "## Hire your admin for $99/month\n\n"
        "$99/month. Billed monthly. \nCancel anytime. Start with a 10-day free trial."
    )
    spans = evidence_quote_bank(raw, limit=6)
    assert "SOC 2 Type II Compliant" in spans
    assert "CASA Tier-2 Certified" in spans
    assert "Google Verified" in spans
    assert "$99/month. Billed monthly. Cancel anytime. Start with a 10-day free trial." in spans
    assert next(i for i, span in enumerate(spans) if "$99/month" in span) < next(
        i for i, span in enumerate(spans) if "1,488" in span
    )
    assert all(span in " ".join(raw.split()) for span in spans)



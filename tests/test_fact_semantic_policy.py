def test_six_quotes_preserve_complete_long_evidence_and_still_need_literal_sources():
    quote = "Astra evaluates the complete task sequence. " * 7 + "It is a company estimate only."
    fact = {
        "text": "Astra оценивает последовательности задач, по заявлению компании.",
        "kind": "capability",
        "document_ids": [1],
        "evidence_quotes": [{"document_id": 1, "quote": quote}],
    }
    compacted = compact_generated_evidence_quotes({"facts": [fact]})["facts"][0]
    assert "".join(q["quote"] for q in compacted["evidence_quotes"]) == quote
    compacted["evidence_quotes"].extend(
        [
            {"document_id": 1, "quote": "Astra evaluates the complete task sequence."},
        ]
        * (6 - len(compacted["evidence_quotes"]))
    )
    parsed = ResearchFact.model_validate(compacted)
    docs = {1: {"source_class": "primary", "content_text": quote}}
    assert fact_safety_errors(parsed, docs) == []
    parsed.evidence_quotes[-1].quote = "Astra changed this quote without permission."
    assert any("literal excerpt" in error for error in fact_safety_errors(parsed, docs))



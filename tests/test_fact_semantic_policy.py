def test_critical_cyber_capability_is_not_security_strength_in_fact_or_card():
    quote = "Astra reaches the Critical level of cybersecurity capability under the Framework."
    bad = "Astra достигла критического уровня кибербезопасности согласно Framework."
    good = "Astra достигла критического уровня возможностей в кибероперациях согласно Framework."
    docs = {1: {"source_class": "primary", "content_text": quote}}
    fact = ResearchFact(
        text=bad,
        document_ids=[1],
        kind="capability",
        evidence_quotes=[
            {"document_id": 1, "quote": quote},
        ],
    )
    assert any("security strength" in error for error in fact_safety_errors(fact, docs))
    assert any(
        "security strength" in error
        for error in fact_safety_errors(
            fact.model_copy(update={"text": "Astra достигла уровня Critical в кибербезопасности."}),
            docs,
        )
    )
    assert fact_safety_errors(fact.model_copy(update={"text": good}), docs) == []
    cited = [{"evidence_quotes": [{"quote": quote}], "source_context": quote}]
    assert any("security strength" in error for error in cited_semantic_errors(bad, cited))
    assert cited_semantic_errors(good, cited) == []
    assert (
        cited_semantic_errors(
            "Критический уровень безопасности требует обновления системы.",
            [{"evidence_quotes": [{"quote": "A security patch protects the system."}]}],
        )
        == []
    )  # The guard needs actual cyber-capability evidence, not a keyword alone.



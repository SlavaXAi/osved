def test_publisher_domain_supports_known_company_but_not_another_product_version():
    quote = "Today, we are releasing GPT‑6 Astra, the most capable model broadly deployed."
    docs = {
        1: {
            "source_class": "primary",
            "publisher": "openai.com",
            "title": "Safety overview: GPT-6 Astra",
            "url": "https://openai.com/index/safety-overview-gpt-6-astra",
            "canonical_url": "https://openai.com/index/safety-overview-gpt-6-astra/",
            "content_text": quote,
        }
    }
    fact = ResearchFact(
        text="OpenAI выпустила GPT-6 Astra и широко развернула модель.",
        kind="release",
        document_ids=[1],
        evidence_quotes=[{"document_id": 1, "quote": quote}],
    )
    assert fact_safety_errors(fact, docs) == []
    for invented in ("GPT-7 Astra", "GPT-6-Max Astra", "GPT-6.1 Astra"):
        errors = fact_safety_errors(
            fact.model_copy(
                update={
                    "text": fact.text.replace("GPT-6 Astra", invented),
                }
            ),
            docs,
        )
        assert any("Latin product" in error for error in errors)
    errors = fact_safety_errors(
        fact.model_copy(
            update={
                "text": fact.text.replace("OpenAI", "Anthropic"),
            }
        ),
        docs,
    )
    assert any("organization" in error for error in errors)
    assert hook_identity_tokens("Safety overview: GPT-6 Astra") == hook_identity_tokens(
        "Safety overview: GPT‑6 Astra"
    )



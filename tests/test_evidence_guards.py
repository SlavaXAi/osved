import pytest

from app.research.evidence_guards import (
    IncompleteAISummaryBlockError,
    author_evidence_text,
    measurement_relation_errors,
)

# The actual document 1074 marker ordering: one start, THREE independently
# disclaimed generated styles, then a shared style-selector footer and author body.
PREFIX = "# WeatherNext 3\n\nAuthor introduction.\n\n"
AUTHOR_BODY = "\n\nEvery day, weather matters.\n\n## Author section\n\nPhysical context remains.\n"
AI_WIDGET = """Read AI-generated summary

First generated paraphrase: invented replacement claim.

Summaries were generated by Google AI. Generative AI is experimental.

- Second generated paraphrase in bullets.

Summaries were generated by Google AI. Generative AI is experimental.

Third generated simplified paraphrase.

Summaries were generated by Google AI. Generative AI is experimental.

#### Explore other styles:

- General summary
- Bullet points
- Basic explainer"""

CRPS_QUOTE = "CRPS improvement of up to 60% against IMERG."
DATA_CONTEXT = "IMERG is NASA satellite precipitation data. A separate figure shows WeatherNext 2."


def test_three_generated_styles_are_removed_but_author_body_is_exactly_retained():
    source = PREFIX + AI_WIDGET + AUTHOR_BODY
    result = author_evidence_text(source)
    assert result == PREFIX + AUTHOR_BODY
    assert "generated paraphrase" not in result
    assert "Summaries were generated" not in result
    assert source.count("Summaries were generated") == 3  # Raw input unchanged.
    assert author_evidence_text(result) == result


@pytest.mark.parametrize(
    "text",
    [
        "An author discusses an AI-generated summary and its limitations.",
        "Summaries were generated by Google AI.\n\nAuthor commentary, without a widget start.",
        "The UI says Read AI-generated summary, but this is a prose quote.",
    ],
)
def test_unmarked_author_text_is_not_blanket_filtered(text):
    assert author_evidence_text(text) == text


@pytest.mark.parametrize(
    "widget",
    [
        "Read AI-generated summary\n\nSuspect summary.\n\nAuthor body may follow.",
        AI_WIDGET.split("#### Explore other styles:")[0],
        AI_WIDGET.replace("- Basic explainer", "- Unknown footer"),
        AI_WIDGET.replace("Summaries were generated by Google AI.", "Unverified origin."),
    ],
)
def test_ambiguous_widget_boundary_fails_explicitly_without_silent_truncation(widget):
    source = PREFIX + widget + AUTHOR_BODY
    with pytest.raises(IncompleteAISummaryBlockError, match="boundary"):
        author_evidence_text(source)
    assert source.endswith(AUTHOR_BODY)


@pytest.mark.parametrize(
    "fact",
    [
        "Google заявила о росте точности прогнозов осадков до 60% против IMERG.",
        "WeatherNext 3 улучшает точность прогнозов до 60% по сравнению с IMERG.",
        "По CRPS точность прогнозов составляет 60%.",
        "CRPS accuracy is 60%.",
    ],
)
def test_crps_relative_improvement_cannot_become_generic_or_absolute_accuracy(fact):
    errors = measurement_relation_errors(fact, CRPS_QUOTE, DATA_CONTEXT)
    assert any("CRPS" in error for error in errors)


def test_imerg_is_not_recast_as_competing_model():
    errors = measurement_relation_errors(
        "Улучшение CRPS до 60% по сравнению с IMERG.", CRPS_QUOTE, DATA_CONTEXT
    )
    assert any("IMERG" in error for error in errors)


@pytest.mark.parametrize(
    "fact",
    [
        "Улучшение CRPS до 60% относительно IMERG.",
        "Улучшение CRPS до 60%; ориентир — IMERG.",
        "Улучшение CRPS до 60% (IMERG).",
        "По данным Google, улучшение CRPS до 60% относительно IMERG.",
    ],
)
def test_quantified_crps_requires_explicit_imerg_data_role_not_comparator_synonyms(fact):
    errors = measurement_relation_errors(fact, CRPS_QUOTE, DATA_CONTEXT)
    assert any("IMERG data role missing" in error for error in errors)


def test_neighboring_figure_cannot_supply_unstated_benchmark_baseline():
    errors = measurement_relation_errors(
        "Улучшение CRPS до 60% по сравнению с WeatherNext 2.", CRPS_QUOTE, DATA_CONTEXT
    )
    assert any("baseline absent" in error for error in errors)


@pytest.mark.parametrize(
    "fact",
    [
        "По данным Google, улучшение CRPS достигает 60% при оценке по данным IMERG.",
        "Google сообщает об улучшении метрики CRPS до 60% на данных IMERG.",
        "The CRPS improvement reaches 60% when evaluated using IMERG data.",
        "Улучшение CRPS до 60% при проверке по измерениям IMERG.",
        "IMERG — спутниковый набор данных. Улучшение CRPS при такой оценке до 60%.",
        "IMERG is satellite observation data. The CRPS improvement reaches 60%.",
        "Улучшение непрерывной ранжированной вероятностной оценки составляет 60%.",
    ],
)
def test_correct_relative_metric_and_dataset_relation_passes(fact):
    assert measurement_relation_errors(fact, CRPS_QUOTE, DATA_CONTEXT) == []


def test_explicit_cited_model_baseline_is_allowed():
    assert (
        measurement_relation_errors(
            "Улучшение CRPS до 60% по сравнению с WeatherNext 2.",
            "CRPS improvement of 60% over WeatherNext 2, evaluated on IMERG data.",
            DATA_CONTEXT,
        )
        == []
    )


@pytest.mark.parametrize(
    "fact,quote",
    [
        ("Accuracy в этом тесте составляет 60%.", "Accuracy is 60% on the test set."),
        ("Цена модели снижена на 60%.", "The model costs 60% less."),
        ("Поставка завершена на 60%.", CRPS_QUOTE),
        ("Улучшение прогнозов в отдельном тесте достигает 60%.", "Forecast skill improves by 60%."),
    ],
)
def test_unrelated_metrics_are_not_blanket_rejected(fact, quote):
    assert measurement_relation_errors(fact, quote, DATA_CONTEXT + CRPS_QUOTE) == []
